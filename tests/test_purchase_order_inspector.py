"""
Read-only inspection of Shopee's My Purchase /user/purchase/ page.

This test is deliberately isolated from the production purchase pipeline.
It opens /user/purchase/ in a separate browser tab, observes the page's own
network traffic, and extracts a structured representation of the checkout/order
that matches a known monitored item.

IMPORTANT
---------
This file is TEST-ONLY. It must not place, pay, cancel, modify, or otherwise
write an order. It does not call Shopee APIs directly; it only observes GET/
POST responses generated by the page itself.

The matcher is designed for the state immediately after Place Order succeeds:

    monitored item
        -> /user/purchase/
        -> get_all_order_and_checkout_list response
        -> checkout_list_detail
        -> info_card.order_list_cards[*]
        -> actual order_id

The checkout ID and Order ID are intentionally treated as different values.
For the successful test order discovered previously:

    checkout_id = 241792195239038
    order_id    = 241792195231162

Run from the repository root:

    python3 tests/test_purchase_order_inspector.py

Optional target selectors can be supplied when the monitored item is not the
known test item:

    --product-name "Exact or partial product name"
    --item-id 52201950487
    --model-id 400189597306
    --shop-id 1680631055
    --checkout-id 241792195239038
    --wait-seconds 5

Selectors may be combined. A candidate must satisfy every selector supplied.
If no selectors are supplied, the known successful test item's fingerprint is
used so that the test can reproduce the discovery shown in the project work.

Chrome must already be running with remote debugging on localhost:9222 and
logged into the Shopee account whose purchase page is being inspected.
"""

