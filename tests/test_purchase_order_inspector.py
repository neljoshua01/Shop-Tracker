def discord_payload_candidate(match: OrderMatch) -> dict[str, Any]:
    """Build a local, non-sending candidate for the future Discord notifier."""
    return {
        "event": "order_created",
        "status": match.status,
        "order_id": match.order_id,
        "checkout_id": match.checkout_id,
        "shop": match.shop_name,
        "seller": match.seller_username,
        "product": match.product_name,
        "variation": match.variation,
        "quantity": match.quantity,
        "item_price_php": round((match.item_price or 0) / 100000, 2) if match.item_price is not None else None,
        "original_price_php": round((match.original_price or 0) / 100000, 2) if match.original_price is not None else None,
        "order_total_php": round(((match.final_total if match.final_total is not None else match.subtotal) or 0) / 100000, 2)
        if (match.final_total is not None or match.subtotal is not None)
        else None,
        "payment_method": match.payment_method,
        "payment_deadline": match.payment_deadline.isoformat() if match.payment_deadline else None,
    }


def print_header(title: str) -> None:
    print("\n" + "=" * 78)
    print(title)
    print("=" * 78)


def collect_candidate_fields(value: Any, path: str = "$", depth: int = 0) -> list[tuple[str, Any]]:
    if depth > MAX_JSON_DEPTH:
        return []
    found: list[tuple[str, Any]] = []
    if isinstance(value, dict):
        for key, child in list(value.items())[:MAX_JSON_ITEMS]:
            key_text = str(key)
            child_path = f"{path}.{key_text}"
            if not key_is_sensitive(key_text) and any(
                marker in key_text.lower()
                for marker in ("order", "checkout", "item", "model", "shop", "price", "total", "payment", "deadline", "status")
            ):
                found.append((child_path, child))
            found.extend(collect_candidate_fields(child, child_path, depth + 1))
    elif isinstance(value, list):
        for index, child in enumerate(value[:MAX_JSON_ITEMS]):
            found.extend(collect_candidate_fields(child, f"{path}[{index}]", depth + 1))
    return found


async def inspect_purchase_page(page: Any, target: Target, wait_seconds: float) -> None:
    observed_responses: list[dict[str, Any]] = []

    async def on_response(response: Any) -> None:
        url = response.url
        lowered = url.lower()
        if ORDER_LIST_ENDPOINT not in lowered:
            return
        if response.status != 200:
            return
        record: dict[str, Any] = {
            "method": getattr(response.request, "method", "GET").upper(),
            "status": response.status,
            "url": url,
            "safe_url": safe_url(url),
            "content_type": "",
            "json": None,
            "json_error": None,
        }
        try:
            record["content_type"] = response.headers.get("content-type", "")
        except Exception:
            pass
        try:
            record["json"] = await response.json()
        except Exception as exc:
            record["json_error"] = str(exc)
        observed_responses.append(record)

    page.on("response", on_response)

    try:
        print_header("SHOPEE PURCHASE ORDER MATCH TEST")
        print(f"Target URL: {PURCHASE_URL}")
        print("Mode      : READ-ONLY / DISCOVERY")
        print("Actions   : NO purchase/payment/cancellation actions")
        print()
        print("TARGET FINGERPRINT")
        print(f"  Product : {target.product_name or '<any>'}")
        print(f"  Item ID : {target.item_id if target.item_id is not None else '<any>'}")
        print(f"  Model ID: {target.model_id if target.model_id is not None else '<any>'}")
        print(f"  Shop ID : {target.shop_id if target.shop_id is not None else '<any>'}")
        print(f"  Checkout: {target.checkout_id if target.checkout_id is not None else '<any>'}")

        print("\n[NAVIGATION] Opening /user/purchase/ in a separate browser tab...")
        await page.goto(PURCHASE_URL, wait_until="domcontentloaded", timeout=30000)
        try:
            await page.wait_for_load_state("networkidle", timeout=10000)
        except Exception:
            pass
        await asyncio.sleep(wait_seconds)

        print_header("PAGE STATE")
        print(f"URL   : {safe_url(page.url)}")
        try:
            print(f"Title : {normalize(await page.title())}")
        except Exception:
            print("Title : <unavailable>")

        body_text = ""
        try:
            body_text = normalize(await page.locator("body").inner_text(timeout=5000))
        except Exception as exc:
            print(f"Body  : <unavailable: {exc}>")
        if body_text:
            print("\nVISIBLE PAGE TEXT")
            print("-" * 78)
            print(body_text[:MAX_BODY_TEXT])
            if len(body_text) > MAX_BODY_TEXT:
                print("... <body text truncated>")

        # The response listener normally captures this request. If Shopee
        # served the page from an already-warmed connection before the listener
        # was attached, DOM inspection below still provides a fallback signal.
        print_header("AUTHORITATIVE ORDER LIST RESPONSE")
        print(f"Matching responses observed: {len(observed_responses)}")

        all_matches: list[OrderMatch] = []
        for response in observed_responses:
            payload = response.get("json")
            for index, container_type, container in iter_order_containers(payload):
                all_matches.extend(
                    build_match(
                        payload,
                        response["url"],
                        index,
                        container_type,
                        container,
                    )
                )

        # De-duplicate repeated responses/cards without hiding the actual
        # checkout-vs-order distinction.
        unique: dict[tuple[Any, ...], OrderMatch] = {}
        for match in all_matches:
            key = (
                match.checkout_id,
                match.order_id,
                match.item_id,
                match.model_id,
                match.shop_id,
                match.product_name,
            )
            unique[key] = match
        all_matches = list(unique.values())

        print(f"Parsed order cards: {len(all_matches)}")
        for index, match in enumerate(all_matches, start=1):
            print(
                f"  [{index}] order_id={match.order_id!r} checkout_id={match.checkout_id!r} "
                f"item_id={match.item_id!r} model_id={match.model_id!r} "
                f"shop_id={match.shop_id!r} status={match.status!r} "
                f"product={normalize(match.product_name or '')[:100]!r}"
            )

        print_header("TARGET MATCHING")
        matched: list[OrderMatch] = []
        for match in all_matches:
            ok, _ = target_matches(match, target)
            if ok:
                matched.append(match)

        if len(matched) == 1:
            print("MATCH STATUS: UNIQUE MATCH FOUND")
            print_match(matched[0])

            if matched[0].order_id is None:
                raise RuntimeError(
                    "Matched checkout has no actual Order ID in order_list_cards[*].order_id."
                )

            print_header("DISCORD PAYLOAD CANDIDATE — NOT SENT")
            print(json.dumps(discord_payload_candidate(matched[0]), ensure_ascii=False, indent=2))

        elif len(matched) > 1:
            print(f"MATCH STATUS: AMBIGUOUS — {len(matched)} matching cards found")
            for match in matched:
                print_match(match)
            raise RuntimeError(
                "More than one order card matched the supplied monitored-item fingerprint. "
                "Add --checkout-id, --item-id, --model-id, or --shop-id to disambiguate."
            )

        else:
            print("MATCH STATUS: NO MATCH FOUND")
            print("\nAvailable order cards were listed above.")
            print("This test will NOT click anything to create or modify an order.")
            raise RuntimeError(
                "The monitored-item fingerprint was not found on /user/purchase/."
            )

        print_header("INSPECTION COMPLETE")
        print("Read-only order discovery succeeded.")
        print("No purchase, payment, cancellation, or write action was performed.")
        print("No Discord request was sent.")

    finally:
        try:
            page.remove_listener("response", on_response)
        except Exception:
            pass


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Read-only Shopee /user/purchase/ order matching test."
    )
    parser.add_argument("--product-name", help="Exact or partial product name to match")
    parser.add_argument("--item-id", type=int, help="Shopee item_id to match")
    parser.add_argument("--model-id", type=int, help="Shopee model_id to match")
    parser.add_argument("--shop-id", type=int, help="Shopee shop_id to match")
    parser.add_argument("--checkout-id", type=int, help="Checkout ID to match")
    parser.add_argument(
        "--wait-seconds",
        type=float,
        default=3.0,
        help="Extra read-only wait after navigation (default: 3 seconds)",
    )
    return parser.parse_args()


def build_target(args: argparse.Namespace) -> Target:
    # If the caller supplied any selector, do not silently mix it with the
    # known successful item's identifiers. This makes alternate tests precise.
    supplied = any(
        value is not None
        for value in (
            args.product_name,
            args.item_id,
            args.model_id,
            args.shop_id,
            args.checkout_id,
        )
    )
    if supplied:
        return Target(
            product_name=args.product_name,
            item_id=args.item_id,
            model_id=args.model_id,
            shop_id=args.shop_id,
            checkout_id=args.checkout_id,
        )

    return Target(
        product_name=DEFAULT_PRODUCT_NAME,
        item_id=DEFAULT_ITEM_ID,
        model_id=DEFAULT_MODEL_ID,
        shop_id=DEFAULT_SHOP_ID,
    )


def main() -> None:
    args = parse_args()
    target = build_target(args)

    runtime = AsyncRuntime.instance()
    engine = BrowserEngine.instance()
    owner = object()

    future = runtime.submit(engine.open_session(owner, "about:blank"))
    session = future.result(timeout=30)
    page = session.page

    try:
        runtime.submit(
            inspect_purchase_page(page, target, max(0.0, args.wait_seconds))
        ).result(timeout=120)
    finally:
        runtime.submit(engine.close_session(owner)).result(timeout=15)


if __name__ == "__main__":
    main()
