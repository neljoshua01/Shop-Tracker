@dataclass(frozen=True)
class Target:
    product_name: str | None = None
    item_id: int | None = None
    model_id: int | None = None
    shop_id: int | None = None
    checkout_id: int | None = None


@dataclass
class OrderMatch:
    source_url: str
    container_index: int
    container_type: str
    checkout_id: int | None = None
    order_id: int | None = None
    status: str | None = None
    status_label: str | None = None
    payment_method: str | None = None
    payment_deadline: datetime | None = None
    payment_deadline_raw: int | float | str | None = None
    shop_id: int | None = None
    shop_name: str | None = None
    seller_username: str | None = None
    item_id: int | None = None
    model_id: int | None = None
    product_name: str | None = None
    variation: str | None = None
    quantity: int | None = None
    item_price: int | None = None
    original_price: int | None = None
    order_price: int | None = None
    subtotal: int | None = None
    final_total: int | None = None
    checkout_status: int | None = None
    raw_card: dict[str, Any] = field(default_factory=dict)


def safe_url(url: str) -> str:
    parsed = urlsplit(url)
    pairs = [(key, "<redacted>") for key, _ in parse_qsl(parsed.query, keep_blank_values=True)]
    return urlunsplit((parsed.scheme, parsed.netloc, parsed.path, urlencode(pairs), ""))


def normalize(value: Any) -> str:
    return " ".join(str(value).split()).strip()


def key_is_sensitive(key: str) -> bool:
    lowered = key.lower()
    return any(marker in lowered for marker in SENSITIVE_KEY_MARKERS)


def int_value(value: Any) -> int | None:
    if isinstance(value, bool) or value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def money_php(value: int | None) -> str:
    if value is None:
        return "<not found>"
    return f"₱{value / 100000:,.2f}"


def parse_timestamp(value: Any) -> datetime | None:
    """Shopee's type-8/type-7 attributes are Unix seconds."""
    number = int_value(value)
    if number is None or number <= 0:
        return None
    try:
        return datetime.fromtimestamp(number, tz=timezone.utc).astimezone()
    except (OverflowError, OSError, ValueError):
        return None


def text_field(obj: Any, *keys: str) -> str | None:
    if not isinstance(obj, dict):
        return None
    for key in keys:
        value = obj.get(key)
        if value is not None and normalize(value):
            return normalize(value)
    return None


def nested_first_item(card: dict[str, Any]) -> dict[str, Any] | None:
    product_info = card.get("product_info")
    if not isinstance(product_info, dict):
        return None
    groups = product_info.get("item_groups")
    if not isinstance(groups, list):
        return None
    for group in groups:
        if not isinstance(group, dict):
            continue
        items = group.get("items")
        if not isinstance(items, list):
            continue
        for item in items:
            if isinstance(item, dict):
                return item
    return None


def payment_info(status: dict[str, Any]) -> tuple[str | None, int | float | str | None, datetime | None]:
    if not isinstance(status, dict):
        return None, None, None

    # The observed payload uses a translation key such as
    # order_status_text_pay_shopee_kredit_by. Keep the raw key because it is
    # the strongest available indication of the payment method without
    # guessing a localized label.
    header = status.get("header_text")
    payment_method = None
    raw_deadline: int | float | str | None = None

    if isinstance(header, dict):
        text_key = normalize(header.get("text", ""))
        if text_key:
            if "shopee_kredit" in text_key.lower() or "spaylater" in text_key.lower():
                payment_method = "SPayLater"
            else:
                payment_method = text_key

        attributes = header.get("attributes")
        if isinstance(attributes, list):
            for attribute in attributes:
                if not isinstance(attribute, dict):
                    continue
                name = normalize(attribute.get("name", "")).lower()
                if name in {"payby_date", "pay_by_date", "payment_deadline", "expire_time"}:
                    raw_deadline = attribute.get("value")
                    break

    deadline = parse_timestamp(raw_deadline)
    return payment_method, raw_deadline, deadline


def iter_order_containers(payload: Any) -> list[tuple[int, str, dict[str, Any]]]:
    """Return checkout/order entries from the authoritative list response."""
    if not isinstance(payload, dict):
        return []

    new_data = payload.get("new_data")
    if not isinstance(new_data, dict):
        return []

    entries = new_data.get("order_or_checkout_data")
    if not isinstance(entries, list):
        return []

    result: list[tuple[int, str, dict[str, Any]]] = []
    for index, entry in enumerate(entries):
        if not isinstance(entry, dict):
            continue
        if isinstance(entry.get("checkout_list_detail"), dict):
            result.append((index, "checkout_list_detail", entry["checkout_list_detail"]))
        elif isinstance(entry.get("order_list_detail"), dict):
            result.append((index, "order_list_detail", entry["order_list_detail"]))
    return result


def build_match(
    payload: Any,
    source_url: str,
    index: int,
    container_type: str,
    container: dict[str, Any],
) -> list[OrderMatch]:
    info = container.get("info_card")
    if not isinstance(info, dict):
        return []

    checkout_id = int_value(info.get("checkout_id"))
    checkout_status = int_value(info.get("checkout_status"))

    status = container.get("status")
    status_label = None
    status_text = None
    if isinstance(status, dict):
        label = status.get("list_view_status_label")
        if isinstance(label, dict):
            status_label = text_field(label, "text")
        header = status.get("header_text")
        if isinstance(header, dict):
            status_text = text_field(header, "text")

    payment_method, raw_deadline, deadline = payment_info(status if isinstance(status, dict) else {})

    order_id_at_container = int_value(info.get("order_id"))
    cards = info.get("order_list_cards")
    if not isinstance(cards, list):
        return []

    matches: list[OrderMatch] = []
    for card in cards:
        if not isinstance(card, dict):
            continue

        # CRITICAL: for checkout_list_detail the actual Order ID is inside the
        # order card. info.order_id is absent in the newly-created state.
        order_id = int_value(card.get("order_id")) or order_id_at_container

        shop = card.get("shop_info")
        if not isinstance(shop, dict):
            shop = {}
        item = nested_first_item(card) or {}

        product_name = text_field(item, "name")
        variation = text_field(item, "model_name")
        item_id = int_value(item.get("item_id"))
        model_id = int_value(item.get("model_id"))
        shop_id = int_value(shop.get("shop_id")) or int_value(item.get("shop_id"))

        match = OrderMatch(
            source_url=source_url,
            container_index=index,
            container_type=container_type,
            checkout_id=checkout_id,
            order_id=order_id,
            status=status_label or status_text,
            status_label=status_label,
            payment_method=payment_method,
            payment_deadline=deadline,
            payment_deadline_raw=raw_deadline,
            shop_id=shop_id,
            shop_name=text_field(shop, "shop_name"),
            seller_username=text_field(shop, "username"),
            item_id=item_id,
            model_id=model_id,
            product_name=product_name,
            variation=variation,
            quantity=int_value(item.get("amount")),
            item_price=int_value(item.get("item_price")),
            original_price=int_value(item.get("price_before_discount")),
            order_price=int_value(item.get("order_price")),
            subtotal=int_value(info.get("subtotal")),
            final_total=int_value(info.get("final_total")),
            checkout_status=checkout_status,
            raw_card=card,
        )
        matches.append(match)

    return matches


def target_matches(match: OrderMatch, target: Target) -> tuple[bool, list[str]]:
    failures: list[str] = []

    if target.checkout_id is not None and match.checkout_id != target.checkout_id:
        failures.append(f"checkout_id {match.checkout_id} != {target.checkout_id}")

    if target.item_id is not None and match.item_id != target.item_id:
        failures.append(f"item_id {match.item_id} != {target.item_id}")

    if target.model_id is not None and match.model_id != target.model_id:
        failures.append(f"model_id {match.model_id} != {target.model_id}")

    if target.shop_id is not None and match.shop_id != target.shop_id:
        failures.append(f"shop_id {match.shop_id} != {target.shop_id}")

    if target.product_name:
        expected = normalize(target.product_name).lower()
        actual = normalize(match.product_name or "").lower()
        if expected not in actual and actual not in expected:
            failures.append("product name does not match")

    return not failures, failures


